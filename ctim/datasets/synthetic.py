def _self_test() -> None:
    import shutil
    import tempfile

    from ctim.dataset import load_dataset

    ds = generate_synthetic(n_users=300, n_links=2500, n_items=60, n_attrs=25,
                            n_comms=6, n_topics=4, seed=7)
    assert ds.n_users == 300 and ds.n_links == 2500
    assert ds.n_items == 60 and ds.n_attrs == 25
    assert len(set(ds.edges)) == 2500, "arcs must be distinct"
    assert all(u != v for u, v in ds.edges), "no self-loops"
    assert all(0 <= u < 300 and 0 <= v < 300 for u, v in ds.edges)
    assert len(ds.item_attrs) == 60
    assert all(0 <= a < 25 for bag in ds.item_attrs for a in bag)
    assert all(bag == sorted(set(bag)) for bag in ds.item_attrs)
    assert ds.n_logs > 0
    assert all(0 <= i < 60 for _u, i, _t in ds.logs)
    assert ds.logs == sorted(ds.logs, key=lambda r: (r[2], r[0], r[1]))
    assert "SYNTHETIC" in ds.notes

    # determinism / seed sensitivity
    same = generate_synthetic(n_users=300, n_links=2500, n_items=60, n_attrs=25,
                              n_comms=6, n_topics=4, seed=7)
    assert same.edges == ds.edges and same.logs == ds.logs
    assert same.item_attrs == ds.item_attrs
    other = generate_synthetic(n_users=300, n_links=2500, n_items=60, n_attrs=25,
                               n_comms=6, n_topics=4, seed=8)
    assert other.edges != ds.edges

    # the planted communities must actually be dense: with p_intra=0.85 the
    # share of intra-community arcs has to dominate.
    intra = sum(1 for u, v in ds.edges if u % 6 == v % 6)
    assert intra / len(ds.edges) > 0.7, intra / len(ds.edges)

    # items of the same topic must share attributes more than random pairs do
    tmp = tempfile.mkdtemp(prefix="ctim-syn-selftest-")
    try:
        out = os.path.join(tmp, "syn")
        save_dataset(ds, out)
        back = load_dataset(out)
        assert back.n_users == ds.n_users and back.n_links == ds.n_links
        assert back.logs == ds.logs and back.item_attrs == ds.item_attrs

        # streaming path must agree with the in-memory path for the same seed
        out2 = os.path.join(tmp, "syn_stream")
        counts = write_synthetic(out2, name="syn", n_users=300, n_links=2500,
                                 n_items=60, n_attrs=25, n_comms=6, n_topics=4,
                                 seed=7)
        streamed = load_dataset(out2)
        assert counts["n_links"] == 2500 and counts["n_logs"] == ds.n_logs
        assert sorted(streamed.edges) == sorted(ds.edges)
        assert streamed.logs == ds.logs
        assert streamed.item_attrs == ds.item_attrs
        assert "SYNTHETIC" in streamed.notes

        # prepare_synthetic end-to-end, small (in-memory branch)
        out3 = os.path.join(tmp, "syn_prep")
        c3 = prepare_synthetic(out3, name="tiny", n_users=120, n_links=600,
                               n_items=30, n_attrs=15, n_comms=4, n_topics=3,
                               seed=3, verbose=False)
        d3 = load_dataset(out3)
        assert d3.n_users == 120 and d3.n_links == 600 and c3["n_links"] == 600

        # a dataset with the paper's Yelp dimensions must be constructible;
        # generating 2.9M arcs takes ~a minute, so the self-test only proves
        # the streaming branch works at a scale above _STREAM_THRESHOLD.
        out4 = os.path.join(tmp, "syn_big")
        c4 = write_synthetic(out4, name="big", n_users=20000, n_links=60000,
                             n_items=500, n_attrs=100, n_comms=50, n_topics=8,
                             seed=11)
        assert c4["n_links"] == 60000 and c4["n_users"] == 20000
        d4 = load_dataset(out4)
        assert d4.n_links == 60000 and len(set(d4.edges)) == 60000
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    # impossible density is rejected rather than looping forever
    try:
        generate_synthetic(n_users=5, n_links=100, n_items=2, n_attrs=3,
                           n_comms=2, n_topics=2, seed=1)
    except ValueError:
        pass
    else:
        raise AssertionError("expected ValueError for an over-dense request")

    print("ctim/datasets/synthetic.py self-test: OK")


if __name__ == "__main__":
    _self_test()
