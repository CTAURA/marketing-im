def generate_synthetic(name: str = "synthetic",
                       n_users: int = 500,
                       n_links: int = 4000,
                       n_items: int = 200,
                       n_attrs: int = 40,
                       n_comms: int = 10,
                       n_topics: int = 8,
                       seed: int = 42,
                       p_intra: float = 0.85,
                       alpha_theta: float = 0.3,
                       beta_psi: float = 0.05,
                       attrs_per_item: int = 6,
                       base_p: float = 0.04,
                       topic_boost: float = 8.0,
                       n_init_seeds: int = 3,
                       max_steps: int = 8,
                       t_start: int = 1_400_000_000,
                       step_seconds: int = 3600) -> Dataset:
    """Return an in-memory synthetic :class:`~ctim.dataset.Dataset`.

    Suitable for tests and the ``--quick`` profile.  For very large requests
    (Yelp scale) prefer :func:`write_synthetic`, which streams to disk instead
    of holding every edge and adoption in memory.
    """
    rng = random.Random(seed)
    st = _Structure(rng, n_users, n_items, n_attrs, n_comms, n_topics,
                    alpha_theta, beta_psi, attrs_per_item)

    edges = list(_gen_edges(rng, st, n_links, p_intra))
    out_adj, in_adj = build_adjacency(n_users, edges)
    logs = list(_gen_logs(rng, st, out_adj, base_p, topic_boost, n_init_seeds,
                          max_steps, t_start, step_seconds))
    logs.sort(key=lambda r: (r[2], r[0], r[1]))
    edges.sort()

    return Dataset(
        name=name,
        n_users=n_users,
        n_items=n_items,
        n_attrs=n_attrs,
        edges=edges,
        out_adj=out_adj,
        in_adj=in_adj,
        logs=logs,
        item_attrs=st.item_attrs,
        source="synthetic generator (ctim.datasets.synthetic, seed={})".format(seed),
        notes="{}  Planted structure: {} communities (p_intra={}), {} topics, "
              "theta_c ~ Dir({}), psi_z ~ Dir({}), {} attribute tokens per item; "
              "adoptions from topic-biased Independent-Cascade "
              "(base_p={}, topic_boost={}).".format(
                  SYNTHETIC_WARNING, n_comms, p_intra, n_topics, alpha_theta,
                  beta_psi, attrs_per_item, base_p, topic_boost),
    )


def write_synthetic(out_dir: str, name: str = "synthetic",
                    n_users: int = 500,
                    n_links: int = 4000,
                    n_items: int = 200,
                    n_attrs: int = 40,
                    n_comms: int = 10,
                    n_topics: int = 8,
                    seed: int = 42,
                    p_intra: float = 0.85,
                    alpha_theta: float = 0.3,
                    beta_psi: float = 0.05,
                    attrs_per_item: int = 6,
                    base_p: float = 0.04,
                    topic_boost: float = 8.0,
                    n_init_seeds: int = 3,
                    max_steps: int = 8,
                    t_start: int = 1_400_000_000,
                    step_seconds: int = 3600,
                    verbose: bool = False) -> Dict[str, int]:
    """Stream a synthetic dataset straight into the canonical files.

    Never builds the full edge/log lists twice, so it scales to the paper's
    Yelp dimensions (366,715 users / 2,949,285 links / 61,184 items) inside a
    few hundred MB.  Returns the produced counts.
    """
    rng = random.Random(seed)
    st = _Structure(rng, n_users, n_items, n_attrs, n_comms, n_topics,
                    alpha_theta, beta_psi, attrs_per_item)
    os.makedirs(out_dir, exist_ok=True)

    # -- graph.tsv (streamed; adjacency built as we go, for the cascades) ----
    out_adj: List[List[int]] = [[] for _ in range(n_users)]
    n_edges = 0
    with open(os.path.join(out_dir, "graph.tsv"), "wt", encoding="utf-8") as fh:
        for u, v in _gen_edges(rng, st, n_links, p_intra):
            fh.write("{}\t{}\n".format(u, v))
            out_adj[u].append(v)
            n_edges += 1
    if verbose:
        print("[synthetic] {:,} arcs written".format(n_edges))

    # -- logs.tsv (canonical format requires ascending t) -------------------
    logs = sorted(_gen_logs(rng, st, out_adj, base_p, topic_boost, n_init_seeds,
                            max_steps, t_start, step_seconds),
                  key=lambda r: (r[2], r[0], r[1]))
    with open(os.path.join(out_dir, "logs.tsv"), "wt", encoding="utf-8") as fh:
        for u, i, t in logs:
            fh.write("{}\t{}\t{}\n".format(u, i, t))
    n_logs = len(logs)
    del logs
    if verbose:
        print("[synthetic] {:,} adoptions written".format(n_logs))

    # -- items.tsv ----------------------------------------------------------
    with open(os.path.join(out_dir, "items.tsv"), "wt", encoding="utf-8") as fh:
        for i in range(n_items):
            fh.write("{}\t{}\n".format(i, ",".join(str(a) for a in st.item_attrs[i])))

    meta = {
        "name": name,
        "n_users": n_users,
        "n_links": n_edges,
        "n_items": n_items,
        "n_attrs": n_attrs,
        "n_logs": n_logs,
        "source": "synthetic generator (ctim.datasets.synthetic, seed={})".format(seed),
        "notes": "{}  Planted structure: {} communities (p_intra={}), {} topics, "
                 "theta_c ~ Dir({}), psi_z ~ Dir({}), {} attribute tokens per item; "
                 "adoptions from topic-biased Independent-Cascade "
                 "(base_p={}, topic_boost={}).".format(
                     SYNTHETIC_WARNING, n_comms, p_intra, n_topics, alpha_theta,
                     beta_psi, attrs_per_item, base_p, topic_boost),
    }
    with open(os.path.join(out_dir, "meta.json"), "wt", encoding="utf-8") as fh:
        json.dump(meta, fh, indent=2, sort_keys=True)
        fh.write("\n")

    return {"n_users": n_users, "n_links": n_edges, "n_items": n_items,
            "n_attrs": n_attrs, "n_logs": n_logs}


def prepare_synthetic(out_dir: str, name: str = "synthetic",
                      n_users: int = 500, n_links: int = 4000,
                      n_items: int = 200, n_attrs: int = 40,
                      n_comms: int = 10, n_topics: int = 8, seed: int = 42,
                      benchmark: Optional[str] = None,
                      verbose: bool = True, **kwargs) -> Dict[str, int]:
    """Generate, write, and print the produced-vs-paper table.

    Uses the in-memory path for small requests (so the returned Dataset-shaped
    counts come from a genuine round-trip) and the streaming path above the
    ``_STREAM_THRESHOLD`` link count.  ``benchmark`` names the SPEC.md Section 8
    row to compare against (e.g. ``"yelp"`` for a Yelp-scaled stand-in).
    """
    t0 = time.time()
    if verbose:
        print("[synthetic] {}".format(SYNTHETIC_WARNING))
        print("[synthetic] target: {:,} users / {:,} links / {:,} items / {} attrs"
              .format(n_users, n_links, n_items, n_attrs))

    if n_links >= _STREAM_THRESHOLD:
        counts = write_synthetic(out_dir, name=name, n_users=n_users,
                                 n_links=n_links, n_items=n_items,
                                 n_attrs=n_attrs, n_comms=n_comms,
                                 n_topics=n_topics, seed=seed, verbose=verbose,
                                 **kwargs)
    else:
        ds = generate_synthetic(name=name, n_users=n_users, n_links=n_links,
                                n_items=n_items, n_attrs=n_attrs,
                                n_comms=n_comms, n_topics=n_topics, seed=seed,
                                **kwargs)
        save_dataset(ds, out_dir)
        counts = {"n_users": ds.n_users, "n_links": ds.n_links,
                  "n_items": ds.n_items, "n_attrs": ds.n_attrs,
                  "n_logs": ds.n_logs}

    if verbose:
        print("[synthetic] written to {}".format(out_dir))
        print()
        print(paper_comparison_table(
            counts, benchmark=benchmark,
            title="{} -- produced vs. paper (SPEC.md Section 8)".format(name)))
        print()
        print("!! SYNTHETIC: dimensions only, not the paper's data.")
        print("[synthetic] done in {:.1f}s".format(time.time() - t0))
    return counts


