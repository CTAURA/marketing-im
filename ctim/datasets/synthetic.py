# Planted structure
# ---------------------------------------------------------------------------


def _dirichlet(rng: random.Random, alpha: float, k: int) -> List[float]:
    """Draw from a symmetric Dirichlet(alpha) of dimension ``k``.

    Standard construction: normalised independent Gamma(alpha, 1) variates.
    ``random.Random.gammavariate`` is stdlib, so no numpy is needed.
    """
    g = [rng.gammavariate(alpha, 1.0) + 1e-300 for _ in range(k)]
    s = sum(g)
    return [x / s for x in g]


def _sample_categorical(rng: random.Random, probs: Sequence[float]) -> int:
    """Inverse-CDF sample from an (already normalised) categorical."""
    r = rng.random()
    acc = 0.0
    for j, p in enumerate(probs):
        acc += p
        if r < acc:
            return j
    return len(probs) - 1


class _Structure:
    """The planted latent variables, drawn once from ``rng``."""

    def __init__(self, rng: random.Random, n_users: int, n_items: int,
                 n_attrs: int, n_comms: int, n_topics: int,
                 alpha_theta: float, beta_psi: float, attrs_per_item: int):
        self.n_users = n_users
        self.n_items = n_items
        self.n_attrs = n_attrs
        self.n_comms = n_comms
        self.n_topics = n_topics

        # near-equal community sizes; comm_of[v] is v's planted community
        self.comm_of = [v % n_comms for v in range(n_users)]
        self.members: List[List[int]] = [[] for _ in range(n_comms)]
        for v in range(n_users):
            self.members[self.comm_of[v]].append(v)

        # Algorithm 1 line 9: theta_c ~ Dir(alpha)
        self.theta = [_dirichlet(rng, alpha_theta, n_topics) for _ in range(n_comms)]
        # Algorithm 1 line 2: psi_z ~ Dir(beta)
        self.psi = [_dirichlet(rng, beta_psi, n_attrs) for _ in range(n_topics)]

        # Algorithm 1 lines 5-6: z_i ~ Mul(phi_i); w_i ~ Mul(psi_{z_i})
        self.item_topic: List[int] = []
        self.item_attrs: List[List[int]] = []
        for _ in range(n_items):
            z = rng.randrange(n_topics)
            self.item_topic.append(z)
            bag: Set[int] = set()
            for _tok in range(attrs_per_item):
                bag.add(_sample_categorical(rng, self.psi[z]))
            self.item_attrs.append(sorted(bag))


def _gen_edges(rng: random.Random, st: _Structure, n_links: int,
               p_intra: float) -> Iterator[Tuple[int, int]]:
    """Yield exactly ``n_links`` distinct non-self directed arcs.

    Uniqueness is enforced with a set of *packed* ints (``u * n + v``) rather
    than tuples: at Yelp scale (2.9M links) that is the difference between
    ~200 MB and ~1 GB.
    """
    n = st.n_users
    seen: Set[int] = set()
    emitted = 0
    # guard against an impossible request (more arcs than the graph can hold)
    max_arcs = n * (n - 1)
    if n_links > max_arcs:
        raise ValueError("cannot draw {} distinct arcs from {} users (max {})"
                         .format(n_links, n, max_arcs))
    attempts = 0
    attempt_budget = 200 * n_links + 10_000
    while emitted < n_links:
        attempts += 1
        if attempts > attempt_budget:
            raise RuntimeError("edge generation stalled: the requested graph is too "
                               "dense for rejection sampling")
        if rng.random() < p_intra:
            c = rng.randrange(st.n_comms)
            group = st.members[c]
            if len(group) < 2:
                continue
            u = group[rng.randrange(len(group))]
            v = group[rng.randrange(len(group))]
        else:
            u = rng.randrange(n)
            v = rng.randrange(n)
        if u == v:
            continue
        key = u * n + v
        if key in seen:
            continue
        seen.add(key)
        emitted += 1
        yield (u, v)


def _gen_logs(rng: random.Random, st: _Structure,
              out_adj: Sequence[Sequence[int]],
              base_p: float, topic_boost: float, n_init_seeds: int,
              max_steps: int, t_start: int, step_seconds: int
              ) -> Iterator[Tuple[int, int, int]]:
    """Yield ``(u, i, t)`` adoptions from a topic/community-biased IC cascade.

    Arc ``(u, v)`` fires for item ``i`` with probability
    ``min(0.9, base_p * (1 + topic_boost * theta[c(v)][z_i]))``: a user adopts
    readily when the item's topic matches their community's planted interest.
    """
    n = st.n_users
    for i in range(st.n_items):
        z = st.item_topic[i]
        # bias the initial seeds toward one community so cascades stay coherent
        c0 = rng.randrange(st.n_comms)
        pool = st.members[c0] or list(range(n))
        active: Set[int] = set()
        frontier: List[int] = []
        for _ in range(n_init_seeds):
            s = pool[rng.randrange(len(pool))]
            if s not in active:
                active.add(s)
                frontier.append(s)
                yield (s, i, t_start + rng.randrange(step_seconds))
        for step in range(1, max_steps + 1):
            nxt: List[int] = []
            for u in frontier:
                for v in out_adj[u]:
                    if v in active:
                        continue
                    p = base_p * (1.0 + topic_boost * st.theta[st.comm_of[v]][z])
                    if p > 0.9:
                        p = 0.9
                    if rng.random() < p:
                        active.add(v)
                        nxt.append(v)
                        yield (v, i, t_start + step * step_seconds
                               + rng.randrange(step_seconds))
            if not nxt:
                break
            frontier = nxt


