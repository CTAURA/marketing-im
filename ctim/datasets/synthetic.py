"""Synthetic dataset generator with planted community + topic structure.

    ===================================================================
    EVERYTHING THIS MODULE PRODUCES IS SYNTHETIC.  It is not Yelp, it is
    not Digg, and it is not derived from any real trace.  It exists for
    (a) unit tests, (b) the ``--quick`` experiment profile, and (c) a
    Yelp-SCALED stand-in when the retired Yelp Dataset Challenge 2014
    snapshot the paper used is unavailable -- which it always is, since
    Yelp no longer distributes it.  Numbers obtained on a synthetic
    stand-in must never be presented as reproducing the paper's Yelp
    results; they only show the pipeline runs at that scale.  Every
    dataset written here says so in ``meta.json["notes"]``.
    ===================================================================

The planted structure mirrors the generative process of Algorithm 1 so that a
correct CTIM implementation can actually recover it:

* users are partitioned into ``n_comms`` communities of near-equal size;
* an arc is intra-community with probability ``p_intra`` -- communities are
  therefore genuinely dense subgraphs, as Eq (19) assumes;
* each community ``c`` draws a topic interest ``theta_c ~ Dir(alpha_theta)``
  over ``n_topics`` topics (SPEC.md Algorithm 1 line 9);
* each topic ``z`` draws an attribute multinomial ``psi_z ~ Dir(beta_psi)``
  over ``n_attrs`` attribute values (Algorithm 1 line 2);
* each item draws a topic and then its attribute bag from that topic's ``psi``
  (Algorithm 1 lines 5-6);
* adoptions are generated by Independent-Cascade diffusion whose per-user
  activation probability is boosted by ``theta_{c(v), z_i}``, so community and
  topic jointly drive who adopts what -- exactly the coupling CTIM learns.

Everything is deterministic given ``seed``: all randomness flows through a
single ``random.Random`` instance.

Standard library only.  Python 3.9 compatible.
"""

